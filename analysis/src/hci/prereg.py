"""Writes analysis/PREREG_DRAFT.md from config.yaml and the power simulation, for editing before posting on OSF.

Everything comes from the agreed study design and the config. Anything awaiting the researcher is marked [confirm].
"""

from __future__ import annotations

from pathlib import Path

from hci.config import ANALYSIS_DIR, Config, config_hash
from hci.power import power_table, required_n


def _power_section(config: Config) -> str:
    table = power_table(config)
    rows = table[(table["true_difference"] == 0) & table["n"].isin(config.power.highlight_n)]
    pivot = rows.pivot_table(index=["sd", "correlation"], columns="n", values="power").round(2).reset_index()
    header = "| SUS SD | Correlation | " + " | ".join(f"N = {n}" for n in config.power.highlight_n) + " |"
    lines = [header, "|" + "---|" * (2 + len(config.power.highlight_n))]
    for _, row in pivot.iterrows():
        lines.append(
            f"| {row['sd']} | {row['correlation']} | "
            + " | ".join(f"{row[n]:.2f}" for n in config.power.highlight_n)
            + " |"
        )
    needed = required_n(table, 0.8)
    needed = needed[needed["true_difference"] == 0]
    known = needed["n_needed"].dropna()
    reach = (
        f"80% power with no true difference is reached at N = {int(known.min())} to {int(known.max())} in the simulated grid"
        if len(known)
        else "80% power is not reached at any simulated size"
    )
    unreached = int(needed["n_needed"].isna().sum())
    lines += [
        "",
        f"{reach} ({', '.join(str(n) for n in config.power.sample_sizes)} simulated"
        + (f"; {unreached} assumption set(s) do not reach 80% within the grid" if unreached and len(known) else "")
        + ").",
    ]
    return "\n".join(lines)


def build_prereg(config: Config) -> str:
    study, targets = config.study, config.targets
    margin = config.evaluation.equivalence_margin
    threshold = study.small_n_threshold
    k_list = ", ".join(str(k) for k in config.preferences.k_values)
    return f"""# Preregistration draft

Draft for editing before posting on OSF, generated by `hci prereg` from `analysis/config.yaml` (config hash `{config_hash(config)[:12]}`). Items marked [confirm] need the researchers' decision.

## Study question

How much feedback does a preference-driven adaptive UI need, and can new users start from the preferences of similar users?

## Hypotheses

- **H1** [confirm]: a personal model reaches {config.preferences.ceiling_fraction:.0%} of a person's self-consistency ceiling well below 250 comparisons. This study can observe at most {max(config.preferences.k_values)} training comparisons, so "well below 250" is assessed as the median k90 being at or below {max(config.preferences.k_values)}. [confirm this reading]
- **H2** [confirm]: a cluster start plus few comparisons matches scratch plus many comparisons. Assessed by comparing cluster_choice at low k with scratch at high k. [confirm which values of k count as "few" and "many"]
- **H3** [confirm]: clusters built from choices predict held-out users better than clusters built from questionnaire answers, tested as the cluster_choice vs cluster_questionnaire contrast at each k. In this one-group design, new users are held-out participants, not people recruited later.
- **H4a**: each adaptive condition (global, cluster5, personalFull) is rated more usable than static on the SUS (primary outcome). Secondary outcomes: SEQ, task time and task success.
- **H4b**: interfaces from cluster5 are as usable as those from personalFull: the cluster5 - personalFull SUS difference lies within ±{margin:g} SUS points.

Research questions: RQ1 (how many comparisons a personal model needs; H1), RQ2 (starting points; H2), RQ3 (choice-based vs questionnaire clusters; H3), RQ4 (adaptive interfaces in use; H4a, H4b).

There are no subgroup analyses. Background items (age, gender, occupation, technology use, reading glasses, reading language, CS/IT background and others) are described only.

## Design

One group of N adults aged 40 or over takes part in two sessions:

- **Session 1 (comparisons)**, about 45 minutes, online or in person, on a laptop or tablet: language choice, information sheet and consent (three statements, all required: read and understood, agree to take part, aged 40 or over), background questionnaire, instructions, practice and the comparison trials. It ends with "we will contact you for the second session".
- **Session 2 (shopping)**, about 60 minutes, in person on the lab laptop: consent re-confirmation, a practice task, 4 shopping tasks each followed by the SEQ and the SUS, and a final ranking of the 4 interfaces.

The models are frozen and the Session 2 plans generated once every non-withdrawn participant has finished Session 1. Eligibility (age 40+) is checked at the start of Session 1; people under 40 are thanked and leave, and only their age and the screening result are kept.

Participants choose English or Urdu before consent; the whole study, including the clips and the shop, is in that language. Urdu is shown right to left.

The interface space has 7 settings and 432 configurations: text size (standard, large, extra large), target size (standard, large), button style (flat, outlined, raised), icon labels (icon only, icon and text), contrast (standard, high), layout (3-column grid, 2-column grid, list) and guidance (none, hints). The base is the first level of each.

Session 1: 70 main trials, 10 repeats (sides swapped, at least 20 trials later) and 2 attention checks, plus practice trials. Each clip shows the base shop changing to a target config within one product category (the scene). Both clips of a trial share the scene and language; scenes are balanced within each participant (within 1), no scene runs more than 2 trials in a row, and a repeat keeps its original's scene.

Session 2 conditions, ordered by balanced Latin squares: static, global, cluster5 and personalFull. The squares balance exactly in groups of 16 participants; with other numbers, position and task stay in every model.

## Questionnaires

- **SUS** (Brooke, 1996): the standard 10 items on a 5-point scale (Strongly disagree to Strongly agree), with "website" in place of "system". Scoring: items 1, 3, 5, 7, 9 contribute (answer - 1), items 2, 4, 6, 8, 10 contribute (5 - answer); the sum x 2.5 gives 0-100. Item answers and the score are stored. Urdu: the researchers' translation, to be replaced by the published Urdu SUS (Anam, Sadiq & Jamil, 2020, IJCSIS 18(6), 73-78) before data collection. [confirm]
- **SEQ** (Sauro & Dumas, 2009): "Overall, how easy or difficult was this task?", 1 (very difficult) to 7 (very easy), in English and Urdu.

## Sample size and power

Sample size: **N = [fill in]** participants. [confirm] The number is not fixed by the design; it is whatever the recruitment window allows, and the reporting rule below follows from it.

- **If N < {threshold}**: RQ2 and RQ3 are reported as exploratory. RQ4 is primarily estimation: the cluster5 - personalFull SUS difference with its 95% CI, drawn against the ±{margin:g} equivalence bounds. The TOST is secondary, and the report states plainly that the study is underpowered for a formal equivalence test.
- **If N >= {threshold}**: the TOST for H4b is primary, with the estimation figure alongside. RQ2 and RQ3 are confirmatory as described below.

Simulated TOST power at the ±{margin:g} SUS-point margin (SUS SD {config.evaluation.sus_sd:g}; about 0.4 SD, from Anam et al., 2020) with no true difference, {config.power.simulations} simulated studies per cell:

{_power_section(config)}

## Exclusions

Every rule is reported with counts and is switchable in the analysis config.

- Practice trials are dropped from all analyses.
- Participants who fail an attention check are excluded from model building and from the primary analyses. They still receive a flagged plan, and a sensitivity analysis keeps them in.
- Responses under {config.cleaning.fast_rt_ms} ms are flagged and reported, not excluded.
- Withdrawn participants are excluded from the models and from Session 2. Their withdrawal and reason are recorded.
- Someone who finishes Session 1 after the freeze is either excluded or receives a plan from the frozen models, flagged as late.
- Participants whose Session 1 data were collected with an earlier version of the platform are flagged (protocol = earlier-version) and kept in; every analysis is repeated without them.

## Preference model

A Bradley-Terry / logistic model, fitted by MAP with a Gaussian prior w ~ N(mu, sigma^2 I), on 10 dummy features with base levels as reference. Nuisance terms: a global left-position bias and, because the clip set identifies it, a global busyness curvature. Configs are scored with w . x only.

A linear busyness term is not included: the number of changed settings is the exact sum of the 10 dummies, so it cannot be separated from the weights. The weights therefore include any general liking for more or less change, and the analysis reports how many targets would move under a range of assumed values.

Prior mean = starting point: 0 for scratch, pooled weights of everyone else for global, and pooled weights of the assigned cluster for the cluster starts.

sigma: one value for all starting points, chosen from {config.model.sigma_grid} by lowest held-out log-loss averaged over all starting points and k. The selection runs inside the other participants, so the held-out person has no influence on it.

## Learning-curve procedure and k90

For each participant: 20 main trials are drawn at random as a test set, and the remaining 50 stay in chronological order as the training pool. Models train on the first k = {k_list} comparisons. This is repeated with {config.preferences.n_splits} random test splits and averaged.

k90 is the smallest k reaching {config.preferences.ceiling_fraction:.0%} of a person's ceiling. Raw self-consistency (share of the 10 repeats where the same clip was chosen) is the primary ceiling. A corrected ceiling, (1 + sqrt(2c - 1)) / 2, is secondary, because a model can legitimately beat test-retest agreement. If 50 comparisons are not enough, k90 is recorded as ">50" and treated as censored. A participant whose {config.preferences.ceiling_fraction:.0%} target is at or below chance is counted as "k90 not meaningful" and left out of the medians.

## Starting points and clusters

All comparisons are leave-one-out: for each participant, the nuisance terms, sigma, global model, clusters and cluster models are rebuilt without that participant.

- Choice-based clusters: k-means on each person's weights, with {" or ".join(str(k) for k in config.clusters.candidates)} clusters chosen by silhouette. A held-out person is assigned by likelihood, using only their first k training comparisons.
- Questionnaire clusters: k-means on the self-rated preference items with the same number of clusters. "No preference" is neutral. A held-out person is assigned from their answers alone, so this start also exists at k = 0.
- The number of clusters (2 or 3) is chosen from the data at freeze time, and a count is allowed only if every cluster has at least {config.clusters.min_cluster_size} people in every leave-one-out fit; otherwise 1 cluster (cluster = global). The choice and its stability (adjusted Rand index across leave-one-out fits and bootstrap resamples) are reported.

## Session 2 conditions and frozen models

- static: no adaptation.
- global: the leave-one-out global model.
- cluster5: cluster assigned from the participant's first {5} main trials, then fine-tuned with those trials.
- personalFull: all their main trials, fitted from scratch.

Targets are restricted to configs with {targets.min_changed}-{targets.max_changed} changed settings from the base. Each adaptive condition applies one change, after {config.plans.trigger_after_ms} ms, so only the target config differs.

An RL agent solves the adaptation MDP exactly by value iteration, and its result is checked against a brute-force search. The models are frozen once, after the last Session 1, and never change after the first Session 2 begins.

Frozen-model hash: [to be added when the models are frozen. The models are built from Session 1 of the same participants, so this hash cannot exist before data collection starts. Record it as a dated amendment before the first Session 2.] [confirm]

## Statistical models and corrections

Learning curves: correct ~ start * log(k) + (1|participant) + (1|test_pair), a mixed-effects logistic model fitted once per test split, with estimates and standard errors averaged across splits. Pairwise contrasts at each k with Holm correction within k. Sensitivity: (start|participant). k = 0 baselines are compared separately, by participant bootstrap. Median k90 per starting point with bootstrap CIs.

Fatigue: consistent ~ half + trial_gap + (1|participant), mixed-effects logistic, with the first half being trials 1-{config.cleaning.fatigue_half_boundary}.

Session 2 (RQ4): SUS, SEQ and log(task time): outcome ~ condition + position + task + language + (1|participant), with study language (English or Urdu) as a covariate; if everyone used one language the term is dropped. Task success (all items found and within budget): the same structure, mixed-effects logistic. Items found is descriptive. H4a contrasts: each adaptive condition vs static, with Holm across the contrasts within each outcome. SUS is the primary outcome.

H4b: cluster5 vs personalFull on SUS, using the mixed-model contrast: the estimate, its 95% CI and its 90% CI with both one-sided tests (TOST) at an equivalence margin of ±{margin:g} SUS points, fixed before any Session 2 data exist. Which of the two is primary follows the sample-size rule above.

Rankings: Friedman test, pairwise Wilcoxon with Holm correction, mean rank per condition and a Plackett-Luce model.

Sensitivity analyses: attention failures kept in; participants with identical cluster5 and personalFull targets left out; participants flagged protocol = earlier-version left out.

Nuisance check (descriptive): share of Option A, median response time and agreement with each person's own weights, by scene and by language.
"""


def write_prereg(config: Config, path: Path | None = None) -> Path:
    target = path or ANALYSIS_DIR / "PREREG_DRAFT.md"
    target.write_text(build_prereg(config), encoding="utf-8")
    return target
