"""Writes analysis/PREREG_DRAFT.md from config.yaml and the power simulation, for editing before posting on OSF.

Everything comes from the agreed study design and the config. Anything awaiting the researcher is marked [confirm].
"""

from __future__ import annotations

from pathlib import Path

from hci.config import ANALYSIS_DIR, Config, config_hash
from hci.power import power_table, required_n


def _power_section(config: Config) -> str:
    table = power_table(config)
    rows = table[(table["true_difference"] == 0) & table["n"].isin(config.power.highlight_n)]
    pivot = rows.pivot_table(index=["sd", "correlation"], columns="n", values="power").round(2).reset_index()
    header = "| QUIS SD | Correlation | " + " | ".join(f"N = {n}" for n in config.power.highlight_n) + " |"
    lines = [header, "|" + "---|" * (2 + len(config.power.highlight_n))]
    for _, row in pivot.iterrows():
        lines.append(
            f"| {row['sd']} | {row['correlation']} | "
            + " | ".join(f"{row[n]:.2f}" for n in config.power.highlight_n)
            + " |"
        )
    needed = required_n(table, 0.8)
    needed = needed[needed["true_difference"] == 0]
    known = needed["n_needed"].dropna()
    lines += [
        "",
        f"Across these assumptions, 80% power with no true difference needs N between {int(known.min())} and {int(known.max())} (simulated sizes: {', '.join(str(n) for n in config.power.sample_sizes)}).",
    ]
    return "\n".join(lines)


def build_prereg(config: Config) -> str:
    study, targets = config.study, config.targets
    margin = config.phase3.equivalence_margin
    full_n = config.phase3.full_tost_n
    k_list = ", ".join(str(k) for k in config.phase2.k_values)
    return f"""# Preregistration draft

Draft for editing before posting on OSF, generated by `hci prereg` from `analysis/config.yaml` (config hash `{config_hash(config)[:12]}`). Items marked [confirm] need the researchers' decision.

## Study question

How much feedback does a preference-driven adaptive UI need, and can new users start from the preferences of similar users?

## Hypotheses

- **H1** [confirm]: a personal model reaches {config.phase2.ceiling_fraction:.0%} of a person's self-consistency ceiling well below 250 comparisons. This study can observe at most {max(config.phase2.k_values)} training comparisons, so "well below 250" is assessed as the median k90 being at or below {max(config.phase2.k_values)}. [confirm this reading]
- **H2** [confirm]: a cluster start plus few comparisons matches scratch plus many comparisons. Assessed by comparing cluster_choice at low k with scratch at high k. [confirm which values of k count as "few" and "many"]
- **H3** [confirm]: clusters built from choices predict held-out users better than clusters built from questionnaire answers, tested as the cluster_choice vs cluster_questionnaire contrast at each k. In this one-group design, new users are held-out participants, not people recruited later.
- **H4a**: adaptive conditions satisfy users more than static, tested as each adaptive condition vs static.
- **H4b**: interfaces from cluster5 satisfy users as much as those from personalFull, tested for equivalence on QUIS.
- **RQ5** (descriptive only): CS and non-CS participants are compared descriptively on preferences, self-consistency, feedback needs and benefit from adaptation, with no significance tests and no confirmatory claims.

## Design

One group of N participants does Session A (comparison trials) and then Session B (4 shopping tasks in differently adapted shops). Default N = {study.n_participants}, minimum {study.n_min}. Every participant finishes Session A before anyone starts Session B.

Session A: 70 main trials, 10 repeats (sides swapped, at least 20 trials later) and 2 attention checks, plus practice trials.

Session B conditions, ordered by balanced Latin squares: static, global, cluster5 and personalFull. Each task is followed by QUIS and UES-SF, and the session ends with a ranking of the 4 interfaces.

## Sample size and power

Planned N = {study.n_participants}, minimum {study.n_min}. Simulated TOST power at the ±{margin:g} margin with no true difference:

{_power_section(config)}

If N is below {full_n}, H4b is reported as estimation with confidence intervals, with the TOST as secondary.

## Exclusions

Every rule is reported with counts and is switchable in the analysis config.

- Practice trials are dropped from all analyses.
- Participants who fail an attention check are excluded from model building and from the primary analyses. They still receive a flagged plan, and a sensitivity analysis keeps them in.
- Responses under {config.cleaning.fast_rt_ms} ms are flagged and reported, not excluded.
- Withdrawn participants are excluded from the models and from Session B. Their withdrawal and reason are recorded.
- Someone who finishes Session A after the freeze is either excluded or receives a plan from the frozen models, flagged as late.

## Preference model

A Bradley-Terry / logistic model, fitted by MAP with a Gaussian prior w ~ N(mu, sigma^2 I), on 8 dummy features with base levels as reference. Nuisance terms: a global left-position bias and, because the clip set identifies it, a global busyness curvature. Configs are scored with w . x only.

A linear busyness term is not included: the number of changed settings is the exact sum of the 8 dummies, so it cannot be separated from the weights. The weights therefore include any general liking for more or less change, and the analysis reports how many targets would move under a range of assumed values.

Prior mean = starting point: 0 for scratch, pooled weights of everyone else for global, and pooled weights of the assigned cluster for the cluster starts.

sigma: one value for all starting points, chosen from {config.model.sigma_grid} by lowest held-out log-loss averaged over all starting points and k. The selection runs inside the other participants, so the held-out person has no influence on it.

## Learning-curve procedure and k90

For each participant: 20 main trials are drawn at random as a test set, and the remaining 50 stay in chronological order as the training pool. Models train on the first k = {k_list} comparisons. This is repeated with {config.phase2.n_splits} random test splits and averaged.

k90 is the smallest k reaching {config.phase2.ceiling_fraction:.0%} of a person's ceiling. Raw self-consistency (share of the 10 repeats where the same clip was chosen) is the primary ceiling. A corrected ceiling, (1 + sqrt(2c - 1)) / 2, is secondary, because a model can legitimately beat test-retest agreement. If 50 comparisons are not enough, k90 is recorded as ">50" and treated as censored. A participant whose {config.phase2.ceiling_fraction:.0%} target is at or below chance is counted as "k90 not meaningful" and left out of the medians.

## Starting points and clusters

All comparisons are leave-one-out: for each participant, the nuisance terms, sigma, global model, clusters and cluster models are rebuilt without that participant.

- Choice-based clusters: k-means on each person's weights, with {" or ".join(str(k) for k in config.clusters.candidates)} clusters chosen by silhouette. A held-out person is assigned by likelihood, using only their first k training comparisons.
- Questionnaire clusters: k-means on the self-rated preference items with the same number of clusters. "No preference" is neutral. A held-out person is assigned from their answers alone, so this start also exists at k = 0.
- Fewer than {config.clusters.min_eligible} eligible participants: 1 cluster (cluster = global).

## Phase 3 conditions and frozen models

- static: no adaptation.
- global: the leave-one-out global model.
- cluster5: cluster assigned from the participant's first {5} main trials, then fine-tuned with those trials.
- personalFull: all their main trials, fitted from scratch.

Targets are restricted to configs with {targets.min_changed}-{targets.max_changed} changed settings from the base. Each adaptive condition applies one change, after {config.plans.trigger_after_ms} ms, so only the target config differs.

An RL agent solves the adaptation MDP exactly by value iteration, and its result is checked against a brute-force search. The models are frozen once, after the last Session A, and never change after Session B begins.

Frozen-model hash: [to be added when the models are frozen. The models are built from Session A of the same participants, so this hash cannot exist before data collection starts. Record it as a dated amendment before the first Session B.] [confirm]

## Statistical models and corrections

Learning curves: correct ~ start * log(k) + (1|participant) + (1|test_pair), a mixed-effects logistic model fitted once per test split, with estimates and standard errors averaged across splits. Pairwise contrasts at each k with Holm correction within k. Sensitivity: (start|participant). k = 0 baselines are compared separately, by participant bootstrap. Median k90 per starting point with bootstrap CIs.

Fatigue: consistent ~ half + trial_gap + (1|participant), mixed-effects logistic, with the first half being trials 1-{config.cleaning.fatigue_half_boundary}.

Phase 3: QUIS, UES-SF and log(task time): outcome ~ condition + position + task + (1|participant). Task success (all 6 items found and within budget): the same structure, mixed-effects logistic. Items found (0-6) is secondary. Contrasts: each adaptive condition vs static, and cluster5 vs personalFull, with Holm across these 4 contrasts within each outcome. QUIS is the primary outcome. [confirm]

H4b: TOST for cluster5 vs personalFull on QUIS, using the mixed-model contrast and its CI, with an equivalence margin of ±{margin:g} scale points, fixed before Phase 3 data exists. The 90% CI and both one-sided tests are reported. [confirm the margin once the licensed QUIS scale is in]

Rankings: Friedman test, pairwise Wilcoxon with Holm correction, mean rank per condition and a Plackett-Luce model.

Sensitivity analyses: attention failures kept in, and participants with identical cluster5 and personalFull targets left out.
"""


def write_prereg(config: Config, path: Path | None = None) -> Path:
    target = path or ANALYSIS_DIR / "PREREG_DRAFT.md"
    target.write_text(build_prereg(config), encoding="utf-8")
    return target
